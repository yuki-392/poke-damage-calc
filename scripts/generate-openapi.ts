import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { parse, stringify } from "yaml";
import { z } from "zod";
import SwaggerParser from "@apidevtools/swagger-parser";
import { apiSchemas } from "../src/lib/contracts/schemas";

// Keep the original handoff untouched. Only the build tool reads it; the app does not.
const reference = parse(readFileSync("design/champions-codex-handoff-v1.0/contracts/openapi-v1.2.yaml", "utf8"));
const api = structuredClone(reference);
api.info.version = "1.2.0-phase1";
api.info.description = "Phase 1 runtime contract. Endpoints are planned, not implemented. Structural checks are generated from Zod; master ID, cross-field, version and UTF-8 byte checks require createContractValidator. No sharing feature.";
api.tags = [{ name: "Public" }, { name: "Calculations" }, { name: "Rankings" }];
api.paths["/api/v1/calculations/{id}"].delete.summary = "Delete owned calculation";
api.components.schemas = Object.fromEntries(Object.entries(apiSchemas).map(([name, schema]) => {
  const json = z.toJSONSchema(schema, { target: "draft-2020-12", reused: "inline" });
  delete json.$schema;
  return [name, json];
}));
api.components.parameters.IfMatch.schema = { $ref: "#/components/schemas/IfMatch" };
api["x-runtime-validation"] = [
  "statPoints sum <= 66; nature ID/vector equality; known and confirmed form/move/item; legal form ability",
  "sourceVersions equality; snapshot/format/regulation match; override keys and forms must match snapshot entries",
  "strict keys; at most 50 overrides; unique ranking IDs, forms and ranks; coherent singles/doubles pair",
  "saved JSON UTF-8 <= 250000 bytes before JSON.parse; no draft fields or results; positive revision",
  "schema validity never certifies game mechanics, provenance evidence, rights, ownership or release readiness",
];
// z.json() generates local definitions. Rebase these refs when embedding in components.
for (const [name, schema] of Object.entries(api.components.schemas)) {
  const visit = (value: unknown): void => {
    if (!value || typeof value !== "object") return;
    if (Array.isArray(value)) { value.forEach(visit); return; }
    const object = value as Record<string, unknown>;
    if (typeof object.$ref === "string" && object.$ref.startsWith("#/$defs/")) object.$ref = `#/components/schemas/${name}/${object.$ref.slice(2)}`;
    Object.values(object).forEach(visit);
  };
  visit(schema);
}
await SwaggerParser.validate(structuredClone(api));
const output = "# Generated by pnpm contracts:generate. Do not edit by hand.\n" + stringify(api, { lineWidth: 120, aliasDuplicateObjects: false });
const path = "contracts/openapi.yaml";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("OpenAPI is stale: run pnpm contracts:generate");
  console.log("PASS: generated OpenAPI, references and runtime schema alignment");
} else {
  mkdirSync("contracts", { recursive: true });
  writeFileSync(path, output);
  console.log(`Generated ${path}`);
}
